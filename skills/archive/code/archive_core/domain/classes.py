# ── 目录序（展示/导出的唯一排序口径）──────────────────────────────
# 为什么要有这一组函数：以前"谁排在前面"这件事在四处各写一遍（Excel 骨架、PDF 页序、
# 交互层重排、全景卡），一旦口径要改就得改四遍、还容易改漏。现在统一从这里取。
#
# 目录序 = ① 类号固定序（一→十，四/九展开成小类）→ ② 类内按成文时间升序（无日期垫后）
#          → ③ 时间并列时按最小照片号兜底（保证结果稳定、可复现）。
# 依据：docs/rules.md §5.1。

# 类号 → 序号（用现成的 VALID_SUBS 顺序，它已与 excel.SKELETON 逐格一致）
CAT_RANK = {c: i for i, c in enumerate(VALID_SUBS)}


def date_key(d) -> tuple:
    """把 {y,m,d} 变成可比较的元组 —— 排序用。

    返回 (0, 年, 月, 日) 或 (1, 0, 0, 0)：
    第一位是"有没有日期"的标记（0=有日期排在前面，1=无日期垫后），
    这样元组直接比大小就得到"日期升序、无日期在最后"，不用写自定义比较函数。
    缺月/缺日按 0 处理（rules §4.1 说"缺月按 1 月"，配合月=0 时整体仍排在最前，
    实际效果一致：同年无月的排在该年最前）。
    """
    d = d or {}
    y = d.get("y")
    if y is None:                                  # 没年 = 没日期 → 垫后
        return (1, 0, 0, 0)
    return (0, y, d.get("m") or 0, d.get("d") or 0)


def dir_sort_key(m: dict) -> tuple:
    """一条材料行在"目录"里的排序键。materials.sort(key=dir_sort_key) 即得目录序。

    用 m 里已有的字段算，不引入新状态：
      - category：类号（认不出来给 99，排在最后而不是报错）
      - date：材料制成时间
      - raw_seqs/members：照片号列表，取最小那个当并列时的兜底（稳定、可复现）
    """
    ms = m.get("raw_seqs") or m.get("members") or [0]
    return (CAT_RANK.get(m.get("category") or "?", 99),
            date_key(m.get("date")),
            min(ms) if ms else 0)


def normalize_category(s) -> str | None:
    """把模型可能输出的各种写法，规整成【合法小类码】；规整不了返回 None。

    例子（模型常乱写）：
      "9-1" / "九一" / "四-1 学历…" / "四一" → 都该归到 四-1 / 九-1 这类合法小类。
    单个“四/九”不算合法小类（四/九必须落到 四-x/九-x）→ 返回 None（= 未定类）。
    """
    if s is None:
        return None
    s = str(s).strip().replace("－", "-").replace("—", "-")   # 全角/长横 → 半角 -
    # 把空格、括号、书名号、逗号等“噪音”全删掉，只剩汉字和数字
    s = re.sub(r"[\s【】\[\]（）()《》、，,。.]", "", s)
    # 汉字数字/阿拉伯数字 → 统一成汉字类号（1→一…10→十）；给 normalize 用
    cn = {"一": "一", "二": "二", "三": "三", "四": "四", "五": "五",
          "六": "六", "七": "七", "八": "八", "九": "九", "十": "十",
          "1": "一", "2": "二", "3": "三", "4": "四", "5": "五",
          "6": "六", "7": "七", "8": "八", "9": "九"}
    # 正则 ^...$ 要求整串是“主类号(可带数字)(可带-数字)”；re.match 从头匹配
    m = re.match(r"^([一二三四五六七八九十\d]+)(?:-(\d))?$", s)
    if not m:
        return None                        # 长得不像类号 → None
    main = cn.get(m.group(1))              # 第 1 段（主类号）转汉字
    if main is None:
        return None
    sub = f"{main}-{m.group(2)}" if m.group(2) else main   # 有 -N → 拼小类
    return sub if sub in VALID_SUBS else None              # 不在合法集里 → None
